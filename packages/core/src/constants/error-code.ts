/**
 * 全局业务错误码。规则: 0 成功; 1xxxx 通用; 2xxxx 鉴权; 3xxxx 卡密。
 * 各模块在此集中登记，避免散落硬编码。
 */
export enum ErrorCode {
  SUCCESS = 0,

  // 通用 1xxxx
  UNKNOWN = 10000,
  VALIDATION_FAILED = 10001,
  NOT_FOUND = 10002,
  FORBIDDEN = 10003,
  RATE_LIMITED = 10004,

  // 鉴权 2xxxx (P2)
  UNAUTHORIZED = 20000,
  INVALID_CREDENTIALS = 20001,
  TOKEN_EXPIRED = 20002,
  TOKEN_INVALID = 20003,
  USER_EXISTS = 20004,
  USER_NOT_FOUND = 20005,
  ACCOUNT_DISABLED = 20006,

  // 卡密 3xxxx (P3)
  CARD_NOT_FOUND = 30000,
  CARD_ALREADY_USED = 30001,
  CARD_EXPIRED = 30002,
  CARD_DISABLED = 30003,
  CARD_SECRET_MISMATCH = 30004,
  CARD_REDEEM_CONFLICT = 30005,
  PRODUCT_NOT_FOUND = 30006,

  // 系统 4xxxx
  CONFIG_NOT_FOUND = 40000,

  // 工作流 5xxxx
  WORKFLOW_NOT_FOUND = 50000,
  EXECUTION_NOT_FOUND = 50001,
  CREDENTIAL_NOT_FOUND = 50002,
  WEBHOOK_NOT_FOUND = 50003,
}
